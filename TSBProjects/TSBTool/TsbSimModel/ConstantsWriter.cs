using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace TsbSimModel
{
    /// <summary>
    /// Writes TSBTool's model constants (the Tsb2Digits/Tsb2Shares/Tsb2TeamDefense and Tsb3.. arrays in
    /// TSB2_TSB3\TSB2_3_Core\TsbSimAutoUpdater.cs) from the two model files, so they're never copied by hand.
    /// With a target file it replaces the block between the first "// ---- generated" line and
    /// "// ---- end of generated constants ----" in place.
    /// </summary>
    public static class ConstantsWriter
    {
        public const string EndMarker = "        // ---- end of generated constants ----";
        private const string StartMarker = "        // ---- generated";

        public static string Block(string tsb2ModelPath, string tsb3ModelPath)
        {
            StringBuilder sb = new StringBuilder();
            Append(sb, "Tsb2", tsb2ModelPath);
            sb.Append("\n");
            Append(sb, "Tsb3", tsb3ModelPath);
            sb.Append(EndMarker + "\n");
            return sb.ToString();
        }

        /// <summary>Replaces the generated block of 'csPath' (TsbSimAutoUpdater.cs), keeping its line endings and BOM.</summary>
        public static void Patch(string csPath, string block)
        {
            byte[] bytes = File.ReadAllBytes(csPath);
            bool bom = bytes.Length > 2 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF;
            string text = Encoding.UTF8.GetString(bytes, bom ? 3 : 0, bytes.Length - (bom ? 3 : 0));
            bool crlf = text.Contains("\r\n");
            string lf = text.Replace("\r\n", "\n");
            int start = lf.IndexOf(StartMarker);
            int end = lf.IndexOf(EndMarker);
            if (start < 0 || end < start)
                throw new InvalidOperationException("'" + csPath + "' has no generated-constants block (markers not found).");
            end = lf.IndexOf('\n', end) + 1;
            lf = lf.Substring(0, start) + block + lf.Substring(end);
            string result = crlf ? lf.Replace("\n", "\r\n") : lf;
            byte[] outBytes = Encoding.UTF8.GetBytes(result);
            using (FileStream fs = File.Create(csPath))
            {
                if (bom) fs.Write(new byte[] { 0xEF, 0xBB, 0xBF }, 0, 3);
                fs.Write(outBytes, 0, outBytes.Length);
            }
        }

        private static void Append(StringBuilder sb, string prefix, string path)
        {
            FittedModel m = ModelFile.Read(path);
            sb.AppendFormat("        // ---- generated by TsbSimModel ('constants') from {0} ----\n", Path.GetFileName(path));
            sb.AppendFormat("        private static readonly DigitModel[] {0}Digits = {{\n", prefix);
            foreach (DigitModel d in m.Digits)
            {
                int nr = d.Ratings.Length;
                string consts;
                if (d.Const == ConstKind.Single)
                    consts = "{ \"\", " + ModelFile.Num(d.Coef[nr]) + " }";
                else
                {
                    List<string> c = new List<string>();
                    for (int i = 0; i < d.Groups.Length; i++)
                        c.Add("{ \"" + d.Groups[i] + "\", " + ModelFile.Num(d.Coef[nr + i]) + " }");
                    consts = string.Join(", ", c.ToArray());
                }
                sb.AppendFormat("            new DigitModel(\"{0}\", new string[] {1}, new double[] {2},\n", d.Name, Strs(d.Ratings), Nums(d.Coef, 0, nr));
                sb.AppendFormat("                new Dictionary<string, double> {{ {0} }},\n", consts);
                sb.AppendFormat("                {0}, {1}, {2}),\n", d.Const == ConstKind.Slot ? "true" : "false", ModelFile.Num(d.Stretch), ModelFile.Num(d.Center));
            }
            sb.Append("        };\n");
            sb.AppendFormat("        private static readonly ShareModel[] {0}Shares = {{\n", prefix);
            foreach (ShareModel s in m.Shares)
            {
                int nr = s.Ratings.Length;
                List<string> slots = new List<string>();
                for (int i = 0; i < s.Positions.Length; i++)
                    slots.Add("{ \"" + s.Positions[i] + "\", " + ModelFile.Num(s.Coef[nr + i]) + " }");
                List<string> factors = new List<string>();
                foreach (KeyValuePair<string, double> kv in s.GroupFactors)
                    factors.Add("{ \"" + kv.Key + "\", " + ModelFile.Num(kv.Value) + " }");
                List<string> groups = new List<string>();
                foreach (KeyValuePair<string, string[]> g in ShareSpec.Groups(s.Kind))
                    foreach (string pos in g.Value)
                        groups.Add("{ \"" + pos + "\", \"" + g.Key + "\" }");
                sb.AppendFormat("            new ShareModel(\"{0}\", new string[] {1}, new double[] {2},\n", s.Kind.Name, Strs(s.Ratings), Nums(s.Coef, 0, nr));
                sb.AppendFormat("                new Dictionary<string, double> {{ {0} }},\n", string.Join(", ", slots.ToArray()));
                sb.AppendFormat("                {0},\n", ModelFile.Num(s.Spread));
                sb.AppendFormat("                new Dictionary<string, double> {{ {0} }},\n", string.Join(", ", factors.ToArray()));
                sb.AppendFormat("                new Dictionary<string, string> {{ {0} }}),\n", string.Join(", ", groups.ToArray()));
            }
            sb.Append("        };\n");
            // team SimData (TSB2): each group's (DL, LB, DB) rating mix, the group weights then the constant
            sb.AppendFormat("        private static readonly TeamDefenseModel[] {0}TeamDefense = {{\n", prefix);
            foreach (TeamDefenseModel t in m.TeamDefense)
            {
                List<string> r = new List<string>(), w = new List<string>();
                for (int g = 0; g < t.MixRatings.Length; g++)
                {
                    r.Add("new string[] " + Strs(t.MixRatings[g]));
                    w.Add("new double[] " + Nums(t.MixWeights[g], 0, t.MixWeights[g].Length));
                }
                sb.AppendFormat("            new TeamDefenseModel(\"{0}\",\n", t.Name);
                sb.AppendFormat("                new string[][] {{ {0} }},\n", string.Join(", ", r.ToArray()));
                sb.AppendFormat("                new double[][] {{ {0} }},\n", string.Join(", ", w.ToArray()));
                sb.AppendFormat("                new double[] {0}, {1}, {2}),\n", Nums(t.Coef, 0, t.Coef.Length), ModelFile.Num(t.Stretch), ModelFile.Num(t.Center));
            }
            sb.Append("        };\n");
            // free agent value (TSB3: Face's last digit) per position group: the ratings' coefficients, then the constant
            sb.AppendFormat("        private static readonly FreeAgentValueModel[] {0}FreeAgentValue = {{\n", prefix);
            foreach (FreeAgentValueModel f in m.FreeAgentValue)
                sb.AppendFormat("            new FreeAgentValueModel(\"{0}\", new string[] {1}, new string[] {2}, new double[] {3}),\n",
                    f.Group, Strs(FreeAgentValueSpec.Slots(f.Group)), Strs(f.Ratings), Nums(f.Coef, 0, f.Coef.Length));
            sb.Append("        };\n");
        }

        private static string Strs(string[] a)
        {
            return "{ " + string.Join(", ", Array.ConvertAll(a, x => "\"" + x + "\"")) + " }";
        }

        private static string Nums(double[] a, int from, int count)
        {
            string[] s = new string[count];
            for (int i = 0; i < count; i++)
                s[i] = ModelFile.Num(a[from + i]);
            return "{ " + string.Join(", ", s) + " }";
        }
    }
}
